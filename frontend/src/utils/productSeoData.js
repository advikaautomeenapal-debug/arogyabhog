/**
 * Resolve product slug from product name or id
 */
export function getProductSlug(productOrId) {
  if (!productOrId) return null;
  const id = typeof productOrId === 'string' ? productOrId : (productOrId.productId || productOrId._id);
  const name = typeof productOrId === 'string' ? productOrId : (productOrId.name || '');

  const slugMap = {
    'PROD-001': 'everyday-soft-multigrain-atta',
    'PROD-002': 'sugar-care-atta',
    'PROD-003': 'thyro-care-atta',
    'PROD-004': 'high-protein-atta',
    'PROD-005': 'vitality-atta',
    'PROD-006': 'my-choice-atta'
  };

  if (slugMap[id]) return slugMap[id];

  const lowerName = name.toLowerCase();
  if (lowerName.includes('everyday') || lowerName.includes('soft')) return 'everyday-soft-multigrain-atta';
  if (lowerName.includes('sugar')) return 'sugar-care-atta';
  if (lowerName.includes('thyro')) return 'thyro-care-atta';
  if (lowerName.includes('protein')) return 'high-protein-atta';
  if (lowerName.includes('vitality')) return 'vitality-atta';
  if (lowerName.includes('choice') || lowerName.includes('custom')) return 'my-choice-atta';

  return null;
}

