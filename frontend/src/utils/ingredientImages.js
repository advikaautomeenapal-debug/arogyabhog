/**
 * Normalizes grain string for robust lookup
 */
function normalizeKey(str) {
  return String(str || '')
    .trim()
    .toLowerCase()
    .replace(/[\(\)\/\-_,]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Resolves visual metadata for any grain object or name
 */
export function getIngredientMeta(grain) {
  if (!grain) {
    return {
      image: '/ingredients/sharbati-wheat.jpg',
      hindiName: '',
      category: 'Whole Grain',
      tagline: 'Nutritious unpolished grain',
      accentColor: '#C9A227',
      keyNutrient: 'Essential Minerals'
    };
  }

  const rawName = typeof grain === 'string' ? grain : (grain.name || grain.ingredientId || '');
  const lowerName = rawName.toLowerCase();
  const clean = normalizeKey(rawName);

  // 1. Direct match in dictionary
  if (INGREDIENT_VISUAL_CATALOG[lowerName]) {
    return INGREDIENT_VISUAL_CATALOG[lowerName];
  }

  // 2. Clean key match
  for (const [key, val] of Object.entries(INGREDIENT_VISUAL_CATALOG)) {
    if (normalizeKey(key) === clean) {
      return val;
    }
  }

  // 3. Partial substring matching
  for (const [key, val] of Object.entries(INGREDIENT_VISUAL_CATALOG)) {
    if (lowerName.includes(key) || key.includes(lowerName)) {
      return val;
    }
  }

  // 4. Default fallback
  return {
    image: '/ingredients/sharbati-wheat.jpg',
    hindiName: typeof grain === 'object' && grain.subtitle ? grain.subtitle : '',
    category: typeof grain === 'object' && grain.category ? grain.category : 'Whole Grain',
    tagline: typeof grain === 'object' && grain.benefits ? grain.benefits : 'Nutritious whole grain',
    accentColor: (typeof grain === 'object' && grain.color) || '#C9A227',
    keyNutrient: 'Dietary Fiber & Minerals'
  };
}

/**
 * Convenient image getter with guaranteed safe fallback
 */
export function getIngredientImage(grain) {
  const meta = getIngredientMeta(grain);
  return meta.image || '/ingredients/sharbati-wheat.jpg';
}

